// Browser -> authenticated Rust handler -> native TOML, without a game session.
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {spawn} from 'node:child_process';
import {resolve,join} from 'node:path';
import {mkdir,mkdtemp,readFile,readdir} from 'node:fs/promises';
const {chromium}=createRequire(import.meta.url)(process.env.PLAYWRIGHT_MODULE||'playwright');
assert.ok(process.env.NATIVE_SETUP_MAP,'Set NATIVE_SETUP_MAP to the map matching the bundled catalogue');
await mkdir('target/native-setup-browser',{recursive:true});
const dir=await mkdtemp(resolve('target/native-setup-browser/run-'));
const server=spawn(process.env.NATIVE_SETUP_BIN||resolve('target/debug/examples/hunt_setup_preview'),[process.env.NATIVE_SETUP_MAP,dir],{stdio:['ignore','pipe','inherit']});
let browser;
try{
 const launch=await new Promise((resolve,reject)=>{
  const timer=setTimeout(()=>reject(Error('Offline setup fixture timeout')),15000);
  server.once('error',reject);server.once('exit',c=>reject(Error('Fixture exited '+c)));
  server.stdout.on('data',chunk=>{const url=String(chunk).match(/http:\/\/127\.0\.0\.1:[^\s]+/);if(url){clearTimeout(timer);resolve(url[0]);}});
 });
 browser=await chromium.launch({headless:true,executablePath:process.env.BROWSER_EXECUTABLE_PATH||undefined});
 const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[],sockets=[];
 page.on('pageerror',e=>errors.push(e.message));page.on('websocket',ws=>sockets.push(ws.url()));
 await page.goto(launch);
 await page.waitForFunction(()=>document.getElementById('native-setup-status')?.textContent.includes('Native configuration only'),{timeout:60000});
 assert.ok(!page.url().includes('setup_token='),'Pairing secret must be removed from visible URL');
 assert.match(await page.locator('#native-hunt-setup h2').textContent(),/OFFLINE FIXTURE/);
 assert.equal(await page.locator('#layout-mode').inputValue(),'reference','Setup starts with the good artwork-guided layout where available');
 await page.locator('[data-hunting-section="destination:dark-cavern"]').click();
 assert.match(await page.locator('#native-setup-choice').textContent(),/Dark Cavern/);
 await page.locator('#native-setup-name').fill('browser-test-hunt');
 const first=Number(await page.locator('[data-hunting-group="destination:dark-cavern"][data-hunting-room]').first().getAttribute('data-hunting-room'));
 assert.ok(first>0);
 const clickRoom=async id=>{await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))));const p=await page.locator(`#map [data-room="${id}"]`).boundingBox();assert.ok(p);await page.mouse.click(p.x+p.width/2,p.y+p.height/2);};
 await page.locator('#native-pick-start').click();await clickRoom(first);
 assert.match(await page.locator('#native-pick-start').textContent(),new RegExp('#'+first));
 await page.locator('#native-pick-field').click();await clickRoom(first);
 assert.match(await page.locator('#native-pick-field').textContent(),new RegExp('#'+first));
 await page.evaluate(()=>{location.hash='room=228&setup_session=1';});
 await page.locator('#map [data-room="228"]').waitFor();
 await page.locator('#fit').click();
 await page.locator('#native-pick-town').click();await clickRoom(228);
 const clickState=await page.evaluate(()=>({status:document.getElementById('native-setup-status').textContent,dialog:document.getElementById('dialog').open,title:document.getElementById('dialog-title').textContent,rooms:[228,285].map(id=>({id,box:document.querySelector(`#map [data-room="${id}"]`)?.getBoundingClientRect().toJSON()})),svg:document.getElementById('map').getAttribute('viewBox'),canvas:document.getElementById('canvas').getBoundingClientRect().toJSON()}));
 assert.match(await page.locator('#native-pick-town').textContent(),/#228/,JSON.stringify(clickState));
 await page.locator('#native-setup-attacks').fill('attack');
 await page.locator('#native-town-commands').fill('town fixture command');
 await page.locator('#native-field-commands').fill('field fixture command');
 await page.locator('#native-setup-ack').check();
 await page.locator('#native-setup-preview').click();
 await page.waitForFunction(()=>!document.getElementById('native-setup-save').disabled);
 const preview=await page.locator('#native-setup-toml').textContent();
 assert.match(preview,/allowed = \[/);assert.match(preview,/resting = 228/);
 assert.match(preview,/\[rest.field\]/);assert.match(preview,/town fixture command/);assert.match(preview,/field fixture command/);
 assert.deepEqual(await readdir(dir),[],'Preview must not write settings');
 await page.locator('#native-setup-save').click();
 await page.waitForFunction(()=>document.getElementById('native-setup-status').textContent.includes('Saved and verified'));
 const file=join(dir,'hunt/profiles/browser-test-hunt.toml');
 const saved=await readFile(file,'utf8');assert.match(saved,/allowed = \[/);
 await page.locator('#native-setup-reload').click();
 await page.waitForFunction(()=>document.getElementById('native-setup-status').textContent.includes('Reloaded browser-test-hunt'));
 assert.equal(await page.locator('#native-setup-toml').textContent(),preview);
 await page.locator('#native-setup-preview').click();
 await page.waitForFunction(()=>!document.getElementById('native-setup-save').disabled);
 await page.locator('#native-setup-save').click();
 await page.waitForFunction(()=>document.getElementById('native-setup-status').textContent.includes('not overwritten'));
 assert.equal(await readFile(file,'utf8'),saved);
 await page.evaluate(id=>{location.hash=`room=${id}&setup_session=1`;},first);
 await page.locator('#fit').click();
 await page.setViewportSize({width:1280,height:800});await page.waitForTimeout(200);
 const bounds=await page.locator('#canvas').boundingBox();
 await page.locator('.hunting-list').evaluate(n=>{n.scrollTop=n.scrollHeight;});
 assert.deepEqual(await page.locator('#canvas').boundingBox(),bounds);
 assert.ok(bounds.height>250,JSON.stringify(await page.evaluate(()=>({canvas:document.getElementById('canvas').getBoundingClientRect().toJSON(),height:innerHeight,main:document.querySelector('main')?.getBoundingClientRect().toJSON()}))));
 assert.equal(await page.evaluate(()=>window.scrollY),0);
 await page.locator('#native-setup-reload').click();
 await page.waitForFunction(()=>document.getElementById('native-setup-status').textContent.includes('Reloaded'));
 await page.locator('.connections').evaluate(n=>{n.scrollTop=0;});
 await mkdir('target/atlas-evidence',{recursive:true});
 await page.screenshot({path:'target/atlas-evidence/native-hunt-setup.png'});
 assert.deepEqual(errors,[]);assert.deepEqual(sockets,[],'Configuration must not open a game-command WebSocket');
 await page.reload();
 await page.waitForFunction(()=>document.getElementById('native-setup-status')?.textContent.includes('Native configuration only'));
 assert.ok(!page.url().includes('setup_token='));
 console.log('PASS native setup: real map clicks, separate recovery commands, preview/save/native reload, overwrite refusal, independent scrolling, no game transport.');
 console.log('Fixture profile: '+file);
}finally{await browser?.close();server.kill('SIGTERM');}
